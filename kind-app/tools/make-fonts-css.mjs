// Builds src/styles/fonts.css: latin + latin-ext + vietnamese only, woff2 only.
// (vietnamese carries U+1EA0–1EF9 = ọ ẹ — Yoruba/Igbo names must render. unicode-range means the browser
//  only downloads a subset when a glyph from it appears.)
import { readFileSync, writeFileSync } from 'node:fs'
const SRC = [
  ['@fontsource-variable/inter', ['index.css']],
  ['@fontsource-variable/newsreader', ['index.css', 'wght-italic.css']],
  ['@fontsource-variable/jetbrains-mono', ['index.css']],
  ['@fontsource/barlow-condensed', ['500.css', '600.css', '700.css']],
]
let out = `/* GENERATED by tools/make-fonts-css.mjs — do not edit. latin + latin-ext + vietnamese, woff2 only. */\n`
let n = 0
for (const [pkg, files] of SRC) for (const f of files) {
  const css = readFileSync(`node_modules/${pkg}/${f}`, 'utf8')
  for (const m of css.matchAll(/\/\*\s*(\S+)\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/g)) {
    if (!/-(latin|latin-ext|vietnamese)-/.test(m[1])) continue
    const block = m[2].replace(/src:\s*url\(\.\/files\/([^)]+\.woff2)\)\s*format\('[^']+'\)[^;]*;/, `src: url(../../node_modules/${pkg}/files/$1) format('woff2');`)
    out += `/* ${m[1]} */\n${block}\n`; n++
  }
}
writeFileSync('src/styles/fonts.css', out)
console.log(n + ' faces,', out.length + ' bytes')
