// KIND v7 · sound-synth — the DSP and the cue library behind src/fx/sound.js.
// Split out so first load pays nothing for it (sound.js pulls this chunk in on the first gesture / at idle).
//
// Everything here only *schedules nodes* on whatever BaseAudioContext it is handed, so the very same code
// plays live and renders offline (OfflineAudioContext) for tools/audio-render.mjs. No audio files, no globals.
//
//   cue(ctx, bus, t0, opts)   bus = { dry, send } (GainNodes made by master.bus());  opts = { rate, seed, step, on, final, tier, pan, lite }
//   schedule(ctx, master, cue, at, opts)   one cue on a master: bus + notes + duck. The live engine and every offline render go through it.
//   Cue bodies are written in "design" seconds and Hz. `rate` (opts.rate) is applied by the voice helpers —
//   pitch × rate, time ÷ rate — so a cue never has to think about it.
//
// One sonic world: D major pentatonic (D E F# A B). Every pitched cue lives on it, so any two can overlap
// without clashing. Timbre = glass: sine + octave, a short FM "ting" on the strike, plate reverb behind.

import { MARKS } from './sound-marks.js'

const TAU = Math.PI * 2
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x))

// ── pitch ────────────────────────────────────────────────────────────────────────────────────────
const PENT = [0, 2, 4, 7, 9]               // semitones above D: D E F# A B
const D4 = 440 * 2 ** (-7 / 12)            // 293.66 Hz
/** Degree k of D-pentatonic. 0 = D4, 1 = E4, 2 = F#4, 3 = A4, 4 = B4, 5 = D5 … ; negatives descend (-5 = D3, -10 = D2). */
export const P = (k) => {
  const o = Math.floor(k / 5), i = ((k % 5) + 5) % 5
  return D4 * 2 ** ((o * 12 + PENT[i]) / 12)
}

// ── deterministic noise ──────────────────────────────────────────────────────────────────────────
const prng = (seed) => {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const assets = new WeakMap()               // ctx → { noise }
const assetsOf = (ctx) => { let a = assets.get(ctx); if (!a) assets.set(ctx, (a = {})); return a }

// The noise and the impulse responses are generated by resumable generators: a slice every 16k samples, so a phone can spread the work over idle time
// and several ticks (a cold JS engine runs these loops 10-100x slower than a warm one) instead of freezing the first tap. run() finishes one in a single go.
const SLICE = 16383
const run = (gen) => { let r; do r = gen.next(); while (!r.done); return r.value }

/** One channel of the shared noise: 2.5 s of pink noise, seamless when looped, RMS ≈ .25. Pink, not white: whooshes stay warm, clicks stay soft. Pure data (no context needed). */
function* noiseGen(sr, c) {
  const N = Math.floor(sr * 2.5), X = 2048
  const r = prng(1234 + c * 77), raw = new Float32Array(N + X)
  let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0
  for (let i = 0; i < raw.length; i++) {
    const w = r() * 2 - 1
    b0 = .99886 * b0 + w * .0555179; b1 = .99332 * b1 + w * .0750759; b2 = .969 * b2 + w * .153852
    b3 = .8665 * b3 + w * .3104856;  b4 = .55 * b4 + w * .5329522;   b5 = -.7616 * b5 - w * .016898
    raw[i] = b0 + b1 + b2 + b3 + b4 + b5 + b6 + w * .5362
    b6 = w * .115926
    if ((i & SLICE) === SLICE) yield
  }
  const d = new Float32Array(N)
  for (let i = 0; i < N; i++) d[i] = raw[i]
  for (let i = 0; i < X; i++) {            // equal-power crossfade of the tail into the head → no loop click
    const w = (i / X) * Math.PI / 2
    d[i] = raw[i] * Math.sin(w) + raw[N + i] * Math.cos(w)
  }
  yield
  let e = 0
  for (let i = 0; i < N; i++) e += d[i] * d[i]
  const k = .25 / Math.sqrt(e / N)
  for (let i = 0; i < N; i++) d[i] *= k
  return d
}
const noiseData = (sr, c) => run(noiseGen(sr, c))
function noiseBuf(ctx) {
  const a = assetsOf(ctx)
  if (a.noise) return a.noise
  const sr = ctx.sampleRate, buf = ctx.createBuffer(2, Math.floor(sr * 2.5), sr)
  for (let c = 0; c < 2; c++) buf.copyToChannel(a.noiseData?.[c] || noiseData(sr, c), c)
  return (a.noise = buf)
}

/** One channel of a reverb impulse response: dense decorrelated noise, exponential decay, a tail that darkens as it ages (air absorption), a short pre-delay.
 *  The decay is a running product and the darkening coefficient is refreshed every 64 samples: same sound, a quarter of the cost. */
function* irGen(sr, { rt = 1.7, pre = .014, bright = 9000, dark = 1800 } = {}, c = 0) {
  const p0 = Math.floor(pre * sr), N = Math.floor((rt * 1.08 + pre) * sr), d = new Float32Array(N), r = prng(9001 + c * 313)
  const dec = Math.exp(-6.91 / (rt * sr)), fade = Math.max(1, .005 * sr)
  let y = 0, env = 1, k = 0
  for (let i = p0; i < N; i++) {
    const n = i - p0
    if ((n & 63) === 0) k = 1 - Math.exp(-TAU * (dark + (bright - dark) * Math.exp(-(n / sr) * 2.4)) / sr)
    y += ((r() * 2 - 1) - y) * k
    d[i] = y * env * (n < fade ? n / fade : 1)
    env *= dec
    if ((i & SLICE) === SLICE) yield
  }
  return d
}
const irData = (sr, p, c) => run(irGen(sr, p, c))
const toBuffer = (ctx, ch) => { const b = ctx.createBuffer(ch.length, ch[0].length, ctx.sampleRate); ch.forEach((d, c) => b.copyToChannel(d, c)); return b }

// ── master chain ─────────────────────────────────────────────────────────────────────────────────
/** Soft ceiling: transparent below .6, tanh knee above, asymptote .96 (-0.35 dBFS). Safety net, not a sound. */
const CLIP = (() => {
  const n = 4097, c = new Float32Array(n), k = .6, s = .36
  for (let i = 0; i < n; i++) {
    const x = (i / (n - 1)) * 2 - 1, a = Math.abs(x)
    c[i] = Math.sign(x) * (a <= k ? a : k + s * Math.tanh((a - k) / s))
  }
  return c
})()

/** User volume 0..1 → linear gain. 1 = the level the cues are designed and measured at; .6 (default) ≈ -5.5 dB. */
export const taper = (v) => clamp(+v || 0, 0, 1) ** 1.3

/**
 * sum → 20 Hz DC/sub blocker → volume → soft compressor → ceiling → destination.
 * Two reverbs: a tight glass-box ROOM for UI micro-cues and a PLATE for verdicts, rewards and heroes.
 *   master.bus(gain, kind) → { dry, send, dispose(), fade(sec) }      kind: 'ui' | 'reward' | 'hero'  (hero bypasses the duck — it causes it)
 *   master.duck(depth, sec, at)    master.setVolume(v)    master.probe() → { left, right, comp }: AnalyserNodes on the output + the compressor (a meter for the playground; built on first call)
 */
export function createMaster(ctx, { volume = 1, assets = null, defer = false } = {}) {
  const sum = ctx.createGain()
  const dcb = ctx.createBiquadFilter(); dcb.type = 'highpass'; dcb.frequency.value = 20; dcb.Q.value = .6
  const vol = ctx.createGain(); vol.gain.value = taper(volume)
  const comp = ctx.createDynamicsCompressor()
  comp.threshold.value = -12; comp.knee.value = 20; comp.ratio.value = 4; comp.attack.value = .006; comp.release.value = .22
  const trim = ctx.createGain(); trim.gain.value = TRIM           // cancels the compressor's fixed makeup gain (+1.24 dB, measured; tools/audio-render.mjs re-checks it)
  const clip = ctx.createWaveShaper(); clip.curve = CLIP; clip.oversample = '2x'
  sum.connect(dcb); dcb.connect(vol); vol.connect(comp); comp.connect(trim); trim.connect(clip); clip.connect(ctx.destination)
  let probe = null
  if (assets) assetsOf(ctx).noiseData = assets.noise

  const later = []                                                // defer: convolvers are loaded by the caller, one per tick (each assignment is a ~20 ms FFT on a desktop)
  const verb = (key, ir, hpF, lpF) => {
    const input = ctx.createGain(), conv = ctx.createConvolver()
    const load = () => { conv.buffer = toBuffer(ctx, assets?.[key] || [irData(ctx.sampleRate, ir, 0), irData(ctx.sampleRate, ir, 1)]) }
    if (defer) later.push(load); else load()
    const hp = ctx.createBiquadFilter(); hp.type = 'highpass'; hp.frequency.value = hpF; hp.Q.value = .5
    const lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = lpF; lp.Q.value = .5
    input.connect(conv); conv.connect(hp); hp.connect(lp); lp.connect(sum)
    return input
  }
  const plate = verb('plate', PLATE, 240, 6200)
  const room = verb('room', ROOM, 320, 7000)

  const duckDry = ctx.createGain(), duckPlate = ctx.createGain(), duckRoom = ctx.createGain()
  duckDry.connect(sum); duckPlate.connect(plate); duckRoom.connect(room)

  return {
    finish: later,
    bus(gain = 1, kind = 'reward') {
      const dry = ctx.createGain(), send = ctx.createGain()
      dry.gain.value = send.gain.value = gain
      if (kind === 'hero') { dry.connect(sum); send.connect(plate) }
      else { dry.connect(duckDry); send.connect(kind === 'ui' ? duckRoom : duckPlate) }
      return {
        dry, send,
        fade(sec = .12) { const t = ctx.currentTime; for (const g of [dry.gain, send.gain]) { g.cancelScheduledValues(t); g.setTargetAtTime(0, t, sec / 3) } },
        dispose() { try { dry.disconnect(); send.disconnect() } catch { /* already gone */ } },
      }
    },
    setVolume(v) { vol.gain.setTargetAtTime(taper(v), ctx.currentTime, .02) },
    probe() {
      if (!probe) {
        const sp = ctx.createChannelSplitter(2), left = ctx.createAnalyser(), right = ctx.createAnalyser()
        left.fftSize = right.fftSize = 1024; left.smoothingTimeConstant = right.smoothingTimeConstant = 0
        clip.connect(sp); sp.connect(left, 0); sp.connect(right, 1)
        probe = { left, right, comp }
      }
      return probe
    },
    duck(depth = .45, sec = 1, at = ctx.currentTime) {
      for (const g of [duckDry.gain, duckPlate.gain, duckRoom.gain]) {
        g.cancelScheduledValues(at)
        g.setTargetAtTime(depth, at, .03)
        g.setTargetAtTime(1, at + sec, .22)
      }
    },
  }
}
const TRIM = 0.867
const PLATE = { rt: 1.45, pre: .014, bright: 9000, dark: 1800 }
const ROOM = { rt: .34, pre: .004, bright: 9000, dark: 3000 }
const tick = () => (globalThis.scheduler?.yield ? globalThis.scheduler.yield() : new Promise((r) => setTimeout(r, 0)))

// Data for the master at the usual device rate, made ahead of time in idle slices (prewarm) so the first tap only has the graph and two convolver loads left.
const warm = { sr: 0, job: null, data: null, done: false }
function* prepare(sr, into) {
  for (let c = 0; c < 2; c++) into.noise[c] = yield* noiseGen(sr, c)
  for (const [key, p] of [['room', ROOM], ['plate', PLATE]]) for (let c = 0; c < 2; c++) into[key][c] = yield* irGen(sr, p, c)
}
function warmStep(sr) {
  if (!warm.job || warm.sr !== sr) { warm.sr = sr; warm.data = { noise: [], plate: [], room: [] }; warm.job = prepare(sr, warm.data); warm.done = false }
  if (!warm.done && warm.job.next().done) warm.done = true
  return warm.done
}
/** Call from idle callbacks until it returns true: generates the noise and impulse responses for `sr` in slices, spending at most budgetMs per call. */
export function prewarm(sr = 48000, budgetMs = 8) {
  const t = performance.now()
  while (!warmStep(sr)) if (performance.now() - t >= budgetMs) return false
  return true
}

/**
 * createMaster for a phone: the same chain, built a slice at a time (whatever prewarm has not already made, the graph, two convolver loads) so the first tap
 * that unlocks audio never freezes the screen. Resolves when the chain is ready to play. trace(name, ms) reports how long each slice held the main thread.
 */
export async function createMasterAsync(ctx, { volume = 1, trace } = {}) {
  const sr = ctx.sampleRate
  let last = performance.now()
  const lap = async (name) => { const n = performance.now(); trace?.(name, n - last); await tick(); last = performance.now() }
  while (!warmStep(sr)) await lap('data')
  const assets = warm.data
  warm.job = null; warm.data = null; warm.done = false                       // the master owns it now (copied into audio buffers below); free the arrays
  await lap('data')
  const m = createMaster(ctx, { volume, assets, defer: true })
  await lap('graph')
  for (const [i, load] of m.finish.entries()) { load(); await lap(i ? 'plate convolver' : 'room convolver') }
  m.finish.length = 0
  return m
}

// ── voices ───────────────────────────────────────────────────────────────────────────────────────
// Glass partials: [ratio, amp, decay multiplier]. The 4.1 is the little inharmonic "ting"; partials above ~5 kHz are dropped.
const GLASS = [[2, .30, .55], [3, .10, .32], [4.1, .045, .10]]
const swells = new Map()
const swell = (skew) => {              // sin(π·u^skew): skew<1 peaks early, >1 builds to a late peak (risers)
  let c = swells.get(skew)
  if (!c) {
    c = new Float32Array(96)
    for (let i = 0; i < 96; i++) c[i] = Math.sin(Math.PI * (i / 95) ** skew)
    swells.set(skew, c)
  }
  return c
}

function voices(ctx, bus, t0, o = {}) {
  const rate = clamp(+o.rate || 1, .5, 2)
  const lite = !!o.lite                                  // data-fx="lite": no stereo-pair or 'ting' layers: a third fewer oscillators for the same tune
  const gpan = clamp(+o.pan || 0, -1, 1) * .8           // opts.pan shifts the whole cue's image (a dock tab on the left sounds on the left)
  const rnd = prng(((o.seed | 0) || 1) * 2654435761)
  const nz = noiseBuf(ctx)
  const T = (x) => t0 + x / rate

  const route = (node, pan = 0, send = 0) => {
    let n = node
    const pp = gpan ? clamp(pan * .5 + gpan, -1, 1) : pan
    if (pp) { const p = ctx.createStereoPanner(); p.pan.value = clamp(pp, -1, 1); n.connect(p); n = p }
    n.connect(bus.dry)
    if (send > 0) { const s = ctx.createGain(); s.gain.value = send; n.connect(s); s.connect(bus.send) }
  }
  /** a → hold → exponential release. Returns the time the voice is inaudible (-60 dB). ak > 1 bends the attack into a power curve (a swell that really builds). */
  const envelope = (g, t, peak, a, hold, tau, ak = 1) => {
    const p = g.gain
    p.setValueAtTime(0, t)
    if (ak > 1 && a > .05) {
      const c = new Float32Array(64)
      for (let i = 0; i < 64; i++) c[i] = peak * (i / 63) ** ak
      p.setValueCurveAtTime(c, t, a)
    } else p.linearRampToValueAtTime(peak, t + a)
    if (hold > 0) p.setValueAtTime(peak, t + a + hold)
    p.setTargetAtTime(0, t + a + hold, tau)
    return t + a + hold + tau * 7
  }

  /** The basic pitched voice. f/f2 Hz (glide f→f2 over `glide`), a attack, hold sustain, tau release constant. wide = ±cents stereo pair. */
  function tone(at, p) {
    const t = T(at), a = (p.a ?? .004) / rate, hold = (p.hold || 0) / rate, tau = (p.tau ?? .15) / rate
    const mix = ctx.createGain()
    const oscs = []
    const mk = (cents, pan, amp) => {
      const os = ctx.createOscillator(); os.type = p.type || 'sine'
      os.frequency.setValueAtTime(p.f * rate, t)
      if (p.f2) os.frequency.exponentialRampToValueAtTime(p.f2 * rate, t + (p.glide ?? .08) / rate)
      if (cents) os.detune.value = cents
      if (p.vib) {
        const l = ctx.createOscillator(), lg = ctx.createGain()
        l.frequency.value = p.vibHz ?? 5.5; lg.gain.value = p.vib; l.connect(lg); lg.connect(os.detune)
        oscs.push(l)
      }
      let out = os
      if (amp !== 1) { const ag = ctx.createGain(); ag.gain.value = amp; os.connect(ag); out = ag }
      if (pan) { const pn = ctx.createStereoPanner(); pn.pan.value = pan; out.connect(pn); pn.connect(mix) } else out.connect(mix)
      oscs.push(os)
    }
    // wide = ±cents: a centre voice plus a detuned pair panned out. Mono-safe — the beat is a slow breath (±2.5 dB), never a tremolo.
    if (p.wide && !lite) { mk(0, 0, 1); mk(-p.wide, -.8, .3); mk(p.wide, .8, .3); mix.gain.value = .8 } else { mk(0, 0, 1); if (p.wide) mix.gain.value = .87 }
    let node = mix
    if (p.lp) {
      const bq = ctx.createBiquadFilter(); bq.type = 'lowpass'; bq.Q.value = p.lpQ ?? .7
      bq.frequency.setValueAtTime(p.lp * rate, t)
      if (p.lpTo) bq.frequency.exponentialRampToValueAtTime(p.lpTo * rate, t + (p.lpT ?? .3) / rate)
      node.connect(bq); node = bq
    }
    const env = ctx.createGain(); node.connect(env)
    const end = envelope(env, t, p.gain ?? .2, a, hold, tau, p.ak)
    for (const os of oscs) { os.start(t); os.stop(end + .02) }
    route(env, p.pan, p.send ?? .2)
  }

  /** Filtered noise. With `tau`: a burst (click, spark, thock). Without: a swell shaped by `skew` over `dur` (whoosh, riser, rumble). */
  function noise(at, p) {
    const t = T(at), type = p.type || 'bandpass'
    const src = ctx.createBufferSource(); src.buffer = nz; src.loop = true
    const bq = ctx.createBiquadFilter(); bq.type = type; bq.Q.value = p.q ?? 1
    bq.frequency.setValueAtTime(p.f0 * rate, t)
    const env = ctx.createGain(); env.gain.value = 0
    src.connect(bq); bq.connect(env)
    let end
    if (p.tau) {
      end = envelope(env, t, p.gain ?? .2, .0012 / rate, 0, p.tau / rate)
      if (p.f1) bq.frequency.exponentialRampToValueAtTime(p.f1 * rate, t + 7 * p.tau / rate)
    } else {
      const d = p.dur / rate
      if (p.f1) bq.frequency.exponentialRampToValueAtTime(p.f1 * rate, t + d)
      const c = swell(p.skew ?? 1), peak = p.gain ?? .2, arr = new Float32Array(c.length)
      for (let i = 0; i < c.length; i++) arr[i] = c[i] * peak
      env.gain.setValueCurveAtTime(arr, t, d)
      end = t + d
    }
    src.start(t, rnd() * 1.4); src.stop(end + .03)
    route(env, p.pan, p.send ?? 0)
  }

  /** Glass strike: a bandpassed noise tick, optionally with a tiny pitched ping. */
  const tick = (at, p = {}) => {
    noise(at, { f0: p.f ?? 3200, q: p.q ?? 5, tau: p.tau ?? .004, gain: p.gain ?? .5, pan: p.pan, send: p.send ?? .06 })
    if (p.ping) tone(at, { f: p.ping, tau: p.pingTau ?? .03, gain: p.pingGain ?? .08, a: .001, pan: p.pan, send: p.send ?? .06 })
  }

  /** Soft low impact: a pitch-dropping tone plus a lowpassed noise body. Padded door, never a drum. type:'triangle' + lp gives it harmonics a phone speaker can reproduce. */
  const thump = (at, p = {}) => {
    const g = p.gain ?? .5
    tone(at, { f: p.f0 ?? 140, f2: p.f1 ?? 50, glide: p.pd ?? .05, tau: p.tau ?? .09, gain: g, a: p.a ?? .005, pan: p.pan, send: p.send ?? 0, type: p.type, lp: p.lp, lpTo: p.lpTo, lpT: p.lpT })
    if (p.body !== 0) noise(at, { f0: p.bodyF ?? 600, q: .7, type: 'lowpass', tau: .022, gain: g * (p.body ?? .3), pan: p.pan, send: p.send ?? 0 })
    if (p.tok) tone(at, { f: p.tokF ?? P(3), f2: (p.tokF ?? P(3)) * .66, glide: .03, tau: .024, gain: g * p.tok, a: .002, pan: p.pan, send: p.send ?? .05 })   // the knock: a short pitched tok where a phone speaker can reproduce it
  }

  /** Glass bell: FM strike that decays to a pure sine in ~100 ms, + octave/twelfth partials, + a detuned stereo pair, + a tick. */
  function bell(at, p) {
    const { f, gain = .2, tau = .4, send = .35, pan = 0, wide = 3, fm = 2.2, ratio = 2, strike = 1 } = p
    const t = T(at), fc = f * rate
    const car = ctx.createOscillator(), mod = ctx.createOscillator(), mg = ctx.createGain(), env = ctx.createGain()
    car.frequency.value = fc; mod.frequency.value = fc * ratio
    mg.gain.setValueAtTime(fc * ratio * fm, t)
    mg.gain.setTargetAtTime(fc * ratio * fm * .04, t, (p.fmTau ?? .03) / rate)
    mod.connect(mg); mg.connect(car.frequency); car.connect(env)
    const end = envelope(env, t, gain, .0015 / rate, 0, tau / rate)
    for (const os of [car, mod]) { os.start(t); os.stop(end + .02) }
    route(env, pan, send)
    for (const [r, amp, tm] of p.partials || GLASS) {
      if (f * r > 5200 || (lite && r > 3.5)) continue
      tone(at, { f: f * r, gain: gain * amp, tau: tau * tm, a: .0015, pan, send })
    }
    if (wide && !lite) {
      const k = 2 ** (wide / 1200)
      tone(at, { f: f * k, gain: gain * .36, tau, a: .002, pan: -.8, send })
      tone(at, { f: f / k, gain: gain * .36, tau, a: .002, pan: .8, send })
    }
    if (strike) tick(at, { f: clamp(f * 3.1, 2200, 4800), q: 4, gain: .22 * strike * (gain / .2), tau: .005, send: .1, pan })
  }

  /** Titanium bell: FM at an inharmonic ratio → metal, not glass. Shield, medal. */
  function metal(at, p) {
    const { f, gain = .2, tau = .5, send = .3, pan = 0, ratio = 1.4142, fm = 1.7 } = p
    const t = T(at), fc = f * rate
    const car = ctx.createOscillator(), mod = ctx.createOscillator(), mg = ctx.createGain(), env = ctx.createGain()
    car.frequency.value = fc; mod.frequency.value = fc * ratio
    mg.gain.setValueAtTime(fc * ratio * fm, t)
    mg.gain.setTargetAtTime(fc * ratio * fm * .12, t, tau / rate * .35)
    mod.connect(mg); mg.connect(car.frequency); car.connect(env)
    const end = envelope(env, t, gain, .001 / rate, 0, tau / rate)
    for (const os of [car, mod]) { os.start(t); os.stop(end + .02) }
    route(env, pan, send)
    tone(at, { f: f * 2, gain: gain * .22, tau: tau * .5, a: .001, pan, send })
    tick(at, { f: clamp(f * 2.6, 2400, 4600), q: 3, gain: .2 * (gain / .2), tau: .006, send: .08, pan })
  }

  /** Warm plucked tone: triangle through a closing lowpass. */
  const pluck = (at, p) => tone(at, { type: 'triangle', a: .002, tau: .26, lp: p.f * 7, lpTo: p.f * 1.6, lpT: .22, lpQ: 1.1, send: .3, ...p })
  /** Slow-attack pad: a wide sine plus a quiet 2nd harmonic. Sine, not triangle: no odd-harmonic honk around 400 Hz, yet the pitch still reads on a phone speaker. */
  const pad = (at, p) => {
    tone(at, { type: 'sine', a: .08, tau: .6, wide: 5, send: .35, ...p, lp: undefined })
    if (!lite) tone(at, { type: 'sine', a: .08, tau: .6, wide: 5, send: .35, ...p, f: p.f * 2, gain: (p.gain ?? .2) * .28, lp: undefined })
  }

  return { tone, noise, tick, thump, bell, metal, pluck, pad, rnd, step: clamp(o.step | 0, 0, 12), on: o.on !== false, final: !!o.final, tier: o.tier }
}

