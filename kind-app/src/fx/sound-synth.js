/** The bus a cue plays on: kind picks the reverb + duck behaviour, meta.level is the cue's own trim. Live and offline both use this. */
export const cueBus = (master, cue, gain = 1) => master.bus(gain * (CUE_META[cue].level ?? 1), CUE_META[cue].kind)

/**
 * One cue, scheduled on a master: its bus, its notes, and the duck it causes. The live engine and every offline render use this one function,
 * so what the audit measures is what the phone plays. Returns { bus, end, busy } in context time: `end` the reverb is out, `busy` the body is over.
 */
export function schedule(ctx, master, cue, at, opts = {}) {
  const meta = CUE_META[cue]
  if (!meta) throw new Error('unknown cue: ' + cue)
  const rate = clamp(+opts.rate || 1, .5, 2)
  const bus = cueBus(master, cue, clamp(opts.gain ?? 1, 0, 2))
  try { CUE[cue](ctx, bus, at, opts) } catch (e) { bus.dispose(); throw e }
  if (meta.duck) master.duck(meta.duck.depth, meta.duck.ms / 1000 / rate, at)
  return { bus, end: at + meta.len / rate, busy: at + meta.body / rate }
}

/**
 * Render one cue through the *real* master chain with an OfflineAudioContext → AudioBuffer (stereo).
 * volume defaults to 1: the reference level the cues are designed and measured at.  prepare(ctx) runs first (the audit counts nodes there).
 */
export async function renderCue(cue, { sampleRate = 48000, volume = 1, tail = 1.2, prepare, ...opts } = {}) {
  const meta = CUE_META[cue]
  if (!meta) throw new Error('unknown cue: ' + cue)
  const rate = clamp(+opts.rate || 1, .5, 2)
  const secs = meta.len / rate + tail + .02
  const ctx = new OfflineAudioContext(2, Math.ceil(secs * sampleRate), sampleRate)
  prepare?.(ctx)
  const master = createMaster(ctx, { volume })
  schedule(ctx, master, cue, .02, { seed: 1, ...opts })
  return ctx.startRendering()
}

/** Render a sequence: steps = [[cue, atMs, opts?], …], the way a screen would fire them (ducks and all). */
export async function renderSequence(steps, { sampleRate = 48000, volume = 1, tail = 1.2, prepare, ...base } = {}) {
  let end = 0
  for (const [cue, ms, o] of steps) {
    const meta = CUE_META[cue]
    if (!meta) throw new Error('unknown cue: ' + cue)
    end = Math.max(end, ms / 1000 + meta.len / clamp(+o?.rate || 1, .5, 2))
  }
  const ctx = new OfflineAudioContext(2, Math.ceil((end + tail + .02) * sampleRate), sampleRate)
  prepare?.(ctx)
  const master = createMaster(ctx, { volume })
  let seed = 1
  for (const [cue, ms, o] of steps) schedule(ctx, master, cue, .02 + ms / 1000, { ...base, ...o, seed: seed++ })
  return ctx.startRendering()
}
